"""Gold-layer recursive hierarchy / Bill of Materials (BOM) explosion SQL for Databricks and Snowflake."""

from __future__ import annotations

import re

from tick.databricks import (
    deduplicate_column_names,
    deduplicate_table_names,
    sanitize_delta_column_name,
)
from tick.models import ColumnInfo, DiscoveryResult, TableInfo
from tick.snowflake import (
    deduplicate_snowflake_columns,
    deduplicate_snowflake_tables,
    sanitize_snowflake_identifier,
)

_QTY_COL_RE = re.compile(
    r"^(?:qty|quantity|qty_per|qty_per_parent|component_qty|usage_qty|bom_qty|menge|unit_qty|ratio)$",
    re.I,
)
_PLANT_COL_RE = re.compile(r"^(?:plant_id|plant_code|plant|site_id|site_code|werks)$", re.I)


def _bt(val: str) -> str:
    return f"`{val.replace('`', '``')}`"


def _dq(val: str) -> str:
    return f'"{val.replace(chr(34), chr(34) * 2)}"'


def _find_quantity_column(tbl: TableInfo) -> ColumnInfo | None:
    for col in tbl.columns:
        if col.canonical_type in {"integer", "decimal", "float"} and _QTY_COL_RE.match(col.name.strip()):
            return col
    return None


def _find_plant_column(tbl: TableInfo) -> ColumnInfo | None:
    for col in tbl.columns:
        if col.profile and any(g.category == "plant_isolation_key" for g in col.profile.governance_findings):
            return col
    for col in tbl.columns:
        if _PLANT_COL_RE.match(col.name.strip()):
            return col
    return None


def get_hierarchy_tables(result: DiscoveryResult) -> list[TableInfo]:
    """Return all discovered base tables carrying a detected recursive hierarchy (BOM/genealogy/tree)."""
    return [t for t in result.tables if t.table_type == "table" and t.hierarchy is not None]


def render_databricks_gold_hierarchies_sql(
    result: DiscoveryResult,
    catalog: str | None = None,
    silver_schema: str = "silver",
    gold_schema: str = "gold",
    max_depth: int = 20,
) -> str:
    """Generate Databricks Spark SQL recursive CTE Gold tables for detected BOMs, lot genealogy & asset trees."""
    cat = catalog or result.config.databricks_catalog
    base_tables = [t for t in result.tables if t.table_type == "table"]
    tbl_name_map = deduplicate_table_names(base_tables)
    hier_tables = get_hierarchy_tables(result)

    lines: list[str] = [
        f"-- Auto-generated by tick: Databricks Gold Recursive Hierarchy / BOM Explosion SQL ({cat}.{gold_schema})",
        f"-- Source database: {result.overview.database_name} ({result.overview.dialect})",
        "",
        f"CREATE SCHEMA IF NOT EXISTS {_bt(cat)}.{_bt(gold_schema)};",
        "",
    ]

    if not hier_tables:
        lines.append("-- No recursive hierarchies (BOMs, lot genealogy, or asset trees) detected in this database.")
        return "\n".join(lines) + "\n"

    for tbl in hier_tables:
        assert tbl.hierarchy is not None
        safe_tbl = tbl_name_map[tbl.full_name]
        col_map = deduplicate_column_names([c.name for c in tbl.columns])
        parent_col = col_map.get(tbl.hierarchy.parent_column, sanitize_delta_column_name(tbl.hierarchy.parent_column))
        child_col = col_map.get(tbl.hierarchy.child_column, sanitize_delta_column_name(tbl.hierarchy.child_column))
        qty_col_obj = _find_quantity_column(tbl)
        plant_col_obj = _find_plant_column(tbl)
        qty_col = col_map[qty_col_obj.name] if qty_col_obj else None
        plant_col = col_map[plant_col_obj.name] if plant_col_obj else None

        safe_max_depth = max(1, int(max_depth))
        silver_fqn = f"{_bt(cat)}.{_bt(silver_schema)}.{_bt(f'silver_{safe_tbl}')}"
        gold_fqn = f"{_bt(cat)}.{_bt(gold_schema)}.{_bt(f'gold_{safe_tbl}_exploded')}"

        cluster_cols = ([_bt(plant_col)] if plant_col else []) + ["`root_node_id`", "`depth`"]
        plant_sel_e = f"    e.{_bt(plant_col)},\n" if plant_col else ""
        plant_sel_r = f"    r.{_bt(plant_col)},\n" if plant_col else ""
        plant_anti_join = f" AND c.{_bt(plant_col)} <=> e.{_bt(plant_col)}" if plant_col else ""
        plant_rec_join = f" AND e.{_bt(plant_col)} <=> r.{_bt(plant_col)}" if plant_col else ""
        plant_final_sel = f"  {_bt(plant_col)},\n" if plant_col else ""

        qty_root_sel = f"    CAST(e.{_bt(qty_col)} AS DOUBLE) AS `edge_qty`,\n    CAST(e.{_bt(qty_col)} AS DOUBLE) AS `extended_qty`,\n" if qty_col else ""
        qty_rec_sel = f"    CAST(e.{_bt(qty_col)} AS DOUBLE) AS `edge_qty`,\n    CAST(r.`extended_qty` * e.{_bt(qty_col)} AS DOUBLE) AS `extended_qty`,\n" if qty_col else ""
        qty_final_sel = "  `edge_qty`,\n  `extended_qty`,\n" if qty_col else ""

        lines.extend(
            [
                f"-- {tbl.full_name} ({tbl.hierarchy.pattern}: {tbl.hierarchy.parent_column} -> {tbl.hierarchy.child_column})",
                f"CREATE OR REPLACE TABLE {gold_fqn}",
                "USING DELTA",
                f"CLUSTER BY ({', '.join(cluster_cols)})",
                "AS",
                "WITH RECURSIVE hierarchy_edges AS (",
                "  SELECT",
                f"{plant_sel_e}    COALESCE(e.{_bt(parent_col)}, e.{_bt(child_col)}) AS `root_node_id`,",
                f"    e.{_bt(parent_col)} AS `parent_node_id`,",
                f"    e.{_bt(child_col)} AS `child_node_id`,",
                f"{qty_root_sel}    1 AS `depth`,",
                f"    CASE WHEN e.{_bt(parent_col)} IS NULL THEN ARRAY(CAST(e.{_bt(child_col)} AS STRING)) ELSE ARRAY(CAST(e.{_bt(parent_col)} AS STRING), CAST(e.{_bt(child_col)} AS STRING)) END AS `path_nodes`",
                f"  FROM {silver_fqn} AS e",
                f"  WHERE e.{_bt(parent_col)} IS NULL OR NOT EXISTS (",
                f"    SELECT 1 FROM {silver_fqn} AS c",
                f"    WHERE c.{_bt(child_col)} = e.{_bt(parent_col)}{plant_anti_join}",
                "  )",
                "  UNION ALL",
                "  SELECT",
                f"{plant_sel_r}    r.`root_node_id`,",
                f"    e.{_bt(parent_col)} AS `parent_node_id`,",
                f"    e.{_bt(child_col)} AS `child_node_id`,",
                f"{qty_rec_sel}    r.`depth` + 1 AS `depth`,",
                f"    CONCAT(r.`path_nodes`, ARRAY(CAST(e.{_bt(child_col)} AS STRING))) AS `path_nodes`",
                "  FROM hierarchy_edges AS r",
                f"  JOIN {silver_fqn} AS e",
                f"    ON e.{_bt(parent_col)} = r.`child_node_id`{plant_rec_join}",
                f"  WHERE e.{_bt(parent_col)} IS NOT NULL",
                f"    AND r.`depth` < {safe_max_depth}",
                f"    AND NOT ARRAY_CONTAINS(r.`path_nodes`, CAST(e.{_bt(child_col)} AS STRING))",
                ")",
                "SELECT",
                f"{plant_final_sel}  `root_node_id`,",
                "  `parent_node_id`,",
                "  `child_node_id`,",
                f"{qty_final_sel}  `depth`,",
                "  ARRAY_JOIN(`path_nodes`, ' -> ') AS `hierarchy_path`,",
                "  CURRENT_TIMESTAMP() AS `_gold_refreshed_at`",
                "FROM hierarchy_edges;",
                "",
            ]
        )

    return "\n".join(lines).rstrip() + "\n"


def render_snowflake_gold_hierarchies_sql(
    result: DiscoveryResult,
    database: str | None = None,
    silver_schema: str = "SILVER",
    gold_schema: str = "GOLD",
    warehouse: str | None = None,
    max_depth: int = 20,
) -> str:
    """Generate Snowflake Gold Dynamic Tables with recursive CTE BOM / genealogy / asset tree explosion."""
    db = database or result.config.snowflake_database
    wh = warehouse or result.config.snowflake_warehouse
    base_tables = [t for t in result.tables if t.table_type == "table"]
    tbl_name_map = deduplicate_snowflake_tables(base_tables)
    hier_tables = get_hierarchy_tables(result)

    lines: list[str] = [
        f"-- Auto-generated by tick: Snowflake Gold Recursive Hierarchy / BOM Explosion Dynamic Tables ({db}.{gold_schema})",
        f"-- Source database: {result.overview.database_name} ({result.overview.dialect})",
        "",
        f"CREATE SCHEMA IF NOT EXISTS {_dq(db)}.{_dq(gold_schema)};",
        "",
    ]

    if not hier_tables:
        lines.append("-- No recursive hierarchies (BOMs, lot genealogy, or asset trees) detected in this database.")
        return "\n".join(lines) + "\n"

    for tbl in hier_tables:
        assert tbl.hierarchy is not None
        safe_tbl = tbl_name_map[tbl.full_name]
        col_map = deduplicate_snowflake_columns([c.name for c in tbl.columns])
        parent_col = col_map.get(tbl.hierarchy.parent_column, sanitize_snowflake_identifier(tbl.hierarchy.parent_column))
        child_col = col_map.get(tbl.hierarchy.child_column, sanitize_snowflake_identifier(tbl.hierarchy.child_column))
        qty_col_obj = _find_quantity_column(tbl)
        plant_col_obj = _find_plant_column(tbl)
        qty_col = col_map[qty_col_obj.name] if qty_col_obj else None
        plant_col = col_map[plant_col_obj.name] if plant_col_obj else None

        safe_max_depth = max(1, int(max_depth))
        silver_fqn = f"{_dq(db)}.{_dq(silver_schema)}.{_dq(f'SILVER_{safe_tbl}')}"
        gold_fqn = f"{_dq(db)}.{_dq(gold_schema)}.{_dq(f'GOLD_{safe_tbl}_EXPLODED')}"

        plant_sel_e = f"    e.{_dq(plant_col)},\n" if plant_col else ""
        plant_sel_r = f"    r.{_dq(plant_col)},\n" if plant_col else ""
        plant_anti_join = f" AND c.{_dq(plant_col)} IS NOT DISTINCT FROM e.{_dq(plant_col)}" if plant_col else ""
        plant_rec_join = f" AND e.{_dq(plant_col)} IS NOT DISTINCT FROM r.{_dq(plant_col)}" if plant_col else ""
        plant_final_sel = f"  {_dq(plant_col)},\n" if plant_col else ""

        qty_root_sel = f"    CAST(e.{_dq(qty_col)} AS FLOAT) AS \"EDGE_QTY\",\n    CAST(e.{_dq(qty_col)} AS FLOAT) AS \"EXTENDED_QTY\",\n" if qty_col else ""
        qty_rec_sel = f"    CAST(e.{_dq(qty_col)} AS FLOAT) AS \"EDGE_QTY\",\n    CAST(r.\"EXTENDED_QTY\" * e.{_dq(qty_col)} AS FLOAT) AS \"EXTENDED_QTY\",\n" if qty_col else ""
        qty_final_sel = "  \"EDGE_QTY\",\n  \"EXTENDED_QTY\",\n" if qty_col else ""

        cte_cols = (
            ([_dq(plant_col)] if plant_col else [])
            + ['"ROOT_NODE_ID"', '"PARENT_NODE_ID"', '"CHILD_NODE_ID"']
            + (['"EDGE_QTY"', '"EXTENDED_QTY"'] if qty_col else [])
            + ['"DEPTH"', '"PATH_NODES"']
        )

        lines.extend(
            [
                f"-- {tbl.full_name} ({tbl.hierarchy.pattern}: {tbl.hierarchy.parent_column} -> {tbl.hierarchy.child_column})",
                f"CREATE OR REPLACE DYNAMIC TABLE {gold_fqn}",
                "  TARGET_LAG = '1 hour'",
                f"  WAREHOUSE = {_dq(wh)}",
                "AS",
                f"WITH RECURSIVE HIERARCHY_EDGES ({', '.join(cte_cols)}) AS (",
                "  SELECT",
                f"{plant_sel_e}    COALESCE(e.{_dq(parent_col)}, e.{_dq(child_col)}) AS \"ROOT_NODE_ID\",",
                f"    e.{_dq(parent_col)} AS \"PARENT_NODE_ID\",",
                f"    e.{_dq(child_col)} AS \"CHILD_NODE_ID\",",
                f"{qty_root_sel}    1 AS \"DEPTH\",",
                f"    IFF(e.{_dq(parent_col)} IS NULL, ARRAY_CONSTRUCT(TO_VARCHAR(e.{_dq(child_col)})), ARRAY_CONSTRUCT(TO_VARCHAR(e.{_dq(parent_col)}), TO_VARCHAR(e.{_dq(child_col)}))) AS \"PATH_NODES\"",
                f"  FROM {silver_fqn} AS e",
                f"  WHERE e.{_dq(parent_col)} IS NULL OR NOT EXISTS (",
                f"    SELECT 1 FROM {silver_fqn} AS c",
                f"    WHERE c.{_dq(child_col)} = e.{_dq(parent_col)}{plant_anti_join}",
                "  )",
                "  UNION ALL",
                "  SELECT",
                f"{plant_sel_r}    r.\"ROOT_NODE_ID\",",
                f"    e.{_dq(parent_col)} AS \"PARENT_NODE_ID\",",
                f"    e.{_dq(child_col)} AS \"CHILD_NODE_ID\",",
                f"{qty_rec_sel}    r.\"DEPTH\" + 1 AS \"DEPTH\",",
                f"    ARRAY_APPEND(r.\"PATH_NODES\", TO_VARCHAR(e.{_dq(child_col)})::VARIANT) AS \"PATH_NODES\"",
                "  FROM HIERARCHY_EDGES AS r",
                f"  JOIN {silver_fqn} AS e",
                f"    ON e.{_dq(parent_col)} = r.\"CHILD_NODE_ID\"{plant_rec_join}",
                f"  WHERE e.{_dq(parent_col)} IS NOT NULL",
                f"    AND r.\"DEPTH\" < {safe_max_depth}",
                f"    AND NOT ARRAY_CONTAINS(TO_VARCHAR(e.{_dq(child_col)})::VARIANT, r.\"PATH_NODES\")",
                ")",
                "SELECT",
                f"{plant_final_sel}  \"ROOT_NODE_ID\",",
                "  \"PARENT_NODE_ID\",",
                "  \"CHILD_NODE_ID\",",
                f"{qty_final_sel}  \"DEPTH\",",
                "  ARRAY_TO_STRING(\"PATH_NODES\", ' -> ') AS \"HIERARCHY_PATH\"",
                "FROM HIERARCHY_EDGES;",
                "",
            ]
        )

    return "\n".join(lines).rstrip() + "\n"
