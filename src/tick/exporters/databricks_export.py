"""Databricks Unity Catalog DDL, Lakeflow Declarative Pipelines (DLT), and sizing exporters."""

from __future__ import annotations

from pathlib import Path

from tick.databricks import (
    deduplicate_column_names,
    deduplicate_table_names,
    map_to_spark_type,
    sanitize_delta_column_name,
)
from tick.models import DiscoveryResult, TableInfo


def _sql_str(val: str) -> str:
    return val.replace("'", "''")


def _spark_sql_str(val: str) -> str:
    """Escape a string literal for Databricks Spark SQL single-quoted expressions."""
    return (
        val.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )


def _escape_docstring(val: str) -> str:
    return val.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').replace("\n", " ").replace("\r", " ")


def _escape_md(val: str | None) -> str:
    if not val:
        return "—"
    return val.replace("|", "\\|").replace("\n", " ").replace("\r", " ")


def _bt(val: str) -> str:
    return f"`{val.replace('`', '``')}`"


def _uc_mask_fn_name(spark_type: str) -> str:
    if spark_type.strip().upper() == "STRING":
        return "mask_sensitive_string"
    return f"mask_sensitive_{sanitize_delta_column_name(spark_type)}"


def _uc_row_filter_fn_name(spark_type: str) -> str:
    if spark_type.strip().upper() == "STRING":
        return "plant_row_filter"
    return f"plant_row_filter_{sanitize_delta_column_name(spark_type)}"


def render_unity_catalog_ddl(
    result: DiscoveryResult,
    catalog: str | None = None,
    schema: str | None = None,
) -> str:
    """Generate Databricks Unity Catalog Delta Lake DDL with Liquid Clustering, CDF, comments, and UC tags."""
    cat = catalog or result.config.databricks_catalog
    sch = schema or result.config.databricks_schema

    lines: list[str] = [
        f"-- Auto-generated by tick for Databricks Unity Catalog ({cat}.{sch})",
        f"-- Source: {result.overview.dialect} ({result.overview.database_name})",
        "",
        f"CREATE CATALOG IF NOT EXISTS {_bt(cat)};",
        f"CREATE SCHEMA IF NOT EXISTS {_bt(cat)}.{_bt(sch)};",
        "",
    ]

    # fqn -> (first_col_name, spark_type, extra_plant_cols)
    row_filter_tables: dict[str, tuple[str, str, list[str]]] = {}
    # (fqn, col_name) -> (spark_type, reasons)
    mask_columns: dict[tuple[str, str], tuple[str, list[str]]] = {}

    base_tables = [t for t in result.tables if t.table_type == "table"]
    tbl_name_map = deduplicate_table_names(base_tables)

    for tbl in base_tables:
        safe_tbl = tbl_name_map[tbl.full_name]
        col_map = deduplicate_column_names([c.name for c in tbl.columns])
        fqn = f"{_bt(cat)}.{_bt(sch)}.{_bt(safe_tbl)}"
        dc = tbl.delta_compatibility

        lines.append(f"-- Source table: {tbl.full_name}" + (f" ({tbl.semantic_name})" if tbl.semantic_name else ""))
        lines.append(f"CREATE TABLE IF NOT EXISTS {fqn} (")

        col_defs: list[str] = []
        for col in tbl.columns:
            cname = col_map[col.name]
            stype = col.spark_type or map_to_spark_type(col.raw_type, col.canonical_type)
            nn = " NOT NULL" if (not col.nullable and col.is_primary_key) else ""
            comment_text = col.business_description or col.comment or (
                f"Source column: {col.name}" if cname != col.name else None
            )
            comment_sql = f" COMMENT '{_sql_str(comment_text)}'" if comment_text else ""
            col_defs.append(f"  {_bt(cname)} {stype}{nn}{comment_sql}")

        # Standard Bronze/Silver audit metadata columns
        col_defs.append("  `_ingested_at` TIMESTAMP COMMENT 'Databricks ingestion timestamp (UTC)'")
        col_defs.append("  `_source_system` STRING COMMENT 'Originating plant / source system identifier'")
        lines.append(",\n".join(col_defs))
        lines.append(")")
        lines.append("USING DELTA")

        if dc and dc.liquid_clustering_keys:
            ckeys = ", ".join(_bt(k) for k in dc.liquid_clustering_keys)
            lines.append(f"CLUSTER BY ({ckeys})")

        tcomment = tbl.business_description or tbl.comment or (
            f"Discovered from {tbl.full_name} (role: {tbl.recommendations.entity_role if tbl.recommendations else 'unknown'})"
        )
        lines.append(f"COMMENT '{_sql_str(tcomment)}'")

        props = [
            "'delta.enableChangeDataFeed' = 'true'",
            "'delta.enableDeletionVectors' = 'true'",
            "'delta.autoOptimize.optimizeWrite' = 'true'",
        ]
        if dc and dc.requires_column_mapping:
            props.append("'delta.columnMapping.mode' = 'name'")
        lines.append("TBLPROPERTIES (")
        lines.append("  " + ",\n  ".join(props))
        lines.append(");")

        # Unity Catalog governance tags
        role = tbl.recommendations.entity_role if tbl.recommendations else "unknown"
        lines.append(f"ALTER TABLE {fqn} SET TAGS ('source_dialect' = '{_sql_str(result.overview.dialect)}', 'entity_role' = '{role}');")

        for col in tbl.columns:
            cname = col_map[col.name]
            stype = col.spark_type or map_to_spark_type(col.raw_type, col.canonical_type)
            if col.profile:
                if col.profile.pii_findings:
                    cat_tag = col.profile.pii_findings[0].category
                    lines.append(
                        f"ALTER TABLE {fqn} ALTER COLUMN {_bt(cname)} SET TAGS ('pii' = 'true', 'pii_category' = '{_sql_str(cat_tag)}');"
                    )
                    entry = mask_columns.setdefault((fqn, cname), (stype, []))
                    reason = f"pii_{cat_tag}"
                    if reason not in entry[1]:
                        entry[1].append(reason)
                for gov in col.profile.governance_findings:
                    lines.append(
                        f"ALTER TABLE {fqn} ALTER COLUMN {_bt(cname)} SET TAGS ('{gov.uc_tag_key}' = '{gov.uc_tag_value}');"
                    )
                    if gov.uc_policy == "row_filter":
                        if fqn not in row_filter_tables:
                            row_filter_tables[fqn] = (cname, stype, [])
                        elif cname != row_filter_tables[fqn][0] and cname not in row_filter_tables[fqn][2]:
                            row_filter_tables[fqn][2].append(cname)
                    elif gov.uc_policy == "column_mask":
                        entry = mask_columns.setdefault((fqn, cname), (stype, []))
                        if gov.uc_tag_value not in entry[1]:
                            entry[1].append(gov.uc_tag_value)

        lines.append("")

    # Governance Policy Stubs (Row Filters for multi-plant isolation & Column Masks for cost/ITAR/PII)
    if row_filter_tables or mask_columns:
        lines.append("-- ============================================================================")
        lines.append("-- Unity Catalog Row-Level Security & Column Masking Policy Templates")
        lines.append("-- Review and customize group names before applying in production.")
        lines.append("-- ============================================================================")
        if row_filter_tables:
            seen_rf_types: list[str] = []
            for _, stype, _ in row_filter_tables.values():
                if stype not in seen_rf_types:
                    seen_rf_types.append(stype)
            for stype in seen_rf_types:
                fn_name = _uc_row_filter_fn_name(stype)
                cmp_expr = (
                    "plant_val = current_user()"
                    if stype.strip().upper() == "STRING"
                    else "CAST(plant_val AS STRING) = current_user()"
                )
                lines.extend(
                    [
                        f"CREATE OR REPLACE FUNCTION {_bt(cat)}.{_bt(sch)}.{fn_name}(plant_val {stype})",
                        "RETURNS BOOLEAN",
                        "RETURN is_account_group_member('global_manufacturing_admins')",
                        f"    OR {cmp_expr}; -- Replace with plant-access lookup table",
                        "",
                    ]
                )
            for fqn, (col_name, stype, extra_cols) in row_filter_tables.items():
                fn_name = _uc_row_filter_fn_name(stype)
                extra_note = (
                    f" -- Additional plant keys skipped (UC allows 1 row filter/table): {', '.join(extra_cols)}"
                    if extra_cols
                    else ""
                )
                lines.append(
                    f"-- ALTER TABLE {fqn} SET ROW FILTER {_bt(cat)}.{_bt(sch)}.{fn_name} ON ({_bt(col_name)});{extra_note}"
                )
            lines.append("")

        if mask_columns:
            mask_items = list(mask_columns.items())[:25]
            seen_mask_types: list[str] = []
            for _, (stype, _) in mask_items:
                if stype not in seen_mask_types:
                    seen_mask_types.append(stype)
            for stype in seen_mask_types:
                fn_name = _uc_mask_fn_name(stype)
                redacted_expr = (
                    "'***REDACTED***'"
                    if stype.strip().upper() == "STRING"
                    else f"CAST(NULL AS {stype})"
                )
                lines.extend(
                    [
                        f"CREATE OR REPLACE FUNCTION {_bt(cat)}.{_bt(sch)}.{fn_name}(val {stype})",
                        f"RETURNS {stype}",
                        f"RETURN CASE WHEN is_account_group_member('sensitive_data_readers') THEN val ELSE {redacted_expr} END;",
                        "",
                    ]
                )
            for (fqn, col_name), (stype, reasons) in mask_items:
                fn_name = _uc_mask_fn_name(stype)
                lines.append(
                    f"-- ALTER TABLE {fqn} ALTER COLUMN {_bt(col_name)} SET MASK {_bt(cat)}.{_bt(sch)}.{fn_name}; -- ({', '.join(reasons)})"
                )
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def render_lakeflow_pipeline_py(
    result: DiscoveryResult,
    catalog: str | None = None,
    bronze_schema: str | None = None,
    silver_schema: str = "silver",
) -> str:
    """Generate a Databricks Lakeflow Declarative Pipeline (DLT) Bronze -> Silver Python file."""
    cat = catalog or result.config.databricks_catalog
    bsch = bronze_schema or result.config.databricks_schema

    lines: list[str] = [
        '"""Auto-generated Databricks Lakeflow Declarative Pipeline (DLT) Bronze -> Silver scaffolding.',
        "",
        f"Source database: {_escape_docstring(result.overview.database_name)} ({_escape_docstring(result.overview.dialect)})",
        f"Target catalog:  {_escape_docstring(cat)} (bronze={_escape_docstring(bsch)}, silver={_escape_docstring(silver_schema)})",
        '"""',
        "",
        "import dlt",
        "from pyspark.sql import functions as F",
        "",
        f"BRONZE_CATALOG = {cat!r}",
        f"BRONZE_SCHEMA = {bsch!r}",
        "",
    ]

    base_tables = [t for t in result.tables if t.table_type == "table"]
    tbl_name_map = deduplicate_table_names(base_tables)

    for tbl in base_tables:
        safe_tbl = tbl_name_map[tbl.full_name]
        col_map = deduplicate_column_names([c.name for c in tbl.columns])
        bronze_src = f"{cat}.{bsch}.{safe_tbl}"
        rec = tbl.recommendations
        dc = tbl.delta_compatibility
        strategy = rec.ingestion_strategy if rec else "full_refresh"
        cluster_cols = dc.liquid_clustering_keys if dc else []

        # Derive @dlt.expect rules from discovered PK / NOT NULL / low-cardinality domains / OT quality
        expectations: dict[str, str] = {}
        for col in tbl.columns:
            cname = col_map[col.name]
            if col.is_primary_key or (not col.nullable and col.profile and col.profile.null_rate == 0.0):
                expectations[f"valid_{cname}_not_null"] = f"`{cname}` IS NOT NULL"
            if (
                col.profile
                and col.profile.cardinality_class == "low"
                and col.canonical_type == "string"
                and 2 <= (col.profile.distinct_count or 0) <= 10
                and col.profile.null_rate < 0.05
                and not col.profile.pii_findings
                and not col.profile.governance_findings
            ):
                vals = ", ".join(
                    "'" + _spark_sql_str(v.value) + "'"
                    for v in col.profile.top_values[:10]
                )
                if vals:
                    expectations[f"valid_{cname}_domain"] = f"`{cname}` IN ({vals})"

        if tbl.telemetry_profile and tbl.telemetry_profile.quality_column:
            qcol = col_map.get(
                tbl.telemetry_profile.quality_column,
                sanitize_delta_column_name(tbl.telemetry_profile.quality_column),
            )
            expectations["good_sensor_quality"] = f"CAST(`{qcol}` AS STRING) NOT IN ('BAD', '0', 'FAULT')"

        # Build Silver transform expressions
        transforms: list[str] = []
        rename_pairs = [
            (col.name, col_map[col.name])
            for col in tbl.columns
            if col.name != col_map[col.name]
        ]
        for orig, safe in rename_pairs:
            transforms.append(f"        .withColumnRenamed({orig!r}, {safe!r})")

        # Legacy date/time parsing transforms (rename both primary and paired column references!)
        seen_stitched: set[str] = set()
        for col in tbl.columns:
            if col.profile and col.profile.legacy_date:
                ld = col.profile.legacy_date
                cname = col_map[col.name]
                if ld.encoding == "hhmmss" and ld.paired_column:
                    continue  # handled by companion date column
                target_col = f"{cname}_ts" if ld.paired_column else f"{cname}_parsed"
                if target_col not in seen_stitched:
                    seen_stitched.add(target_col)
                    expr = ld.spark_expression
                    if col.name != cname:
                        expr = expr.replace(f"F.col({col.name!r})", f"F.col({cname!r})")
                    if ld.paired_column:
                        paired_safe = col_map.get(
                            ld.paired_column, sanitize_delta_column_name(ld.paired_column)
                        )
                        if ld.paired_column != paired_safe:
                            expr = expr.replace(
                                f"F.col({ld.paired_column!r})", f"F.col({paired_safe!r})"
                            )
                    transforms.append(f"        .withColumn({target_col!r}, {expr})")

        # Decide between AUTO CDC (apply_changes) vs Streaming/Materialized Silver table
        raw_pks = tbl.primary_key or (rec.primary_key_candidates[:1] if rec else [])
        pk_cols = [col_map.get(p, sanitize_delta_column_name(p)) for p in raw_pks]
        wm_col = (
            col_map.get(
                rec.watermark_candidates[0].column,
                sanitize_delta_column_name(rec.watermark_candidates[0].column),
            )
            if (rec and rec.watermark_candidates)
            else None
        )

        lines.append(f"# --- {tbl.full_name}" + (f" ({tbl.semantic_name})" if tbl.semantic_name else "") + f" [{strategy}] ---")
        if tbl.hierarchy:
            lines.append(
                f"# NOTE: Recursive {tbl.hierarchy.pattern} detected ({tbl.hierarchy.parent_column} -> {tbl.hierarchy.child_column})."
            )
            lines.append("# Build a downstream Gold BOM/genealogy explosion model using recursive CTEs.")

        # Full-refresh tables must use batch reads (Materialized Views) so Bronze overwrites do not break streaming
        use_streaming = (
            strategy in {"incremental_merge", "incremental_append", "cdc"}
            or bool(tbl.telemetry_profile)
        )

        # Staging cleaned view
        stage_fn = f"clean_{safe_tbl}"
        lines.append(f"@dlt.view(name={stage_fn!r})")
        if expectations:
            limited_exp = dict(list(expectations.items())[:8])
            lines.append(f"@dlt.expect_all({limited_exp!r})")
        lines.append(f"def {stage_fn}():")
        read_call = "spark.readStream.table" if use_streaming else "spark.read.table"
        lines.append(f"    df = {read_call}({bronze_src!r})")
        if transforms:
            lines.append("    df = (")
            lines.append("        df")
            lines.extend(transforms)
            lines.append("    )")
        lines.append("    return df")
        lines.append("")

        silver_name = f"silver_{safe_tbl}"
        if strategy == "incremental_merge" and pk_cols and wm_col:
            cluster_arg = f", cluster_by={cluster_cols!r}" if cluster_cols else ""
            comment_val = f"Silver deduplicated table for {tbl.full_name}"
            lines.append(
                f"dlt.create_streaming_table(name={silver_name!r}, comment={comment_val!r}{cluster_arg})"
            )
            lines.append("dlt.apply_changes(")
            lines.append(f"    target={silver_name!r},")
            lines.append(f"    source={stage_fn!r},")
            lines.append(f"    keys={pk_cols!r},")
            lines.append(f"    sequence_by=F.col({wm_col!r}),")
            lines.append("    stored_as_scd_type=1,")
            lines.append(")")
        else:
            cluster_arg = f", cluster_by={cluster_cols!r}" if cluster_cols else ""
            comment_val = f"Silver table for {tbl.full_name}"
            lines.append(
                f"@dlt.table(name={silver_name!r}, comment={comment_val!r}{cluster_arg})"
            )
            lines.append(f"def {silver_name}():")
            if tbl.telemetry_profile:
                ts_c = col_map.get(
                    tbl.telemetry_profile.timestamp_column,
                    sanitize_delta_column_name(tbl.telemetry_profile.timestamp_column),
                )
                delay = tbl.telemetry_profile.recommended_watermark_delay
                lines.append(
                    f"    return dlt.read_stream({stage_fn!r}).withWatermark({ts_c!r}, {delay!r})"
                )
            elif use_streaming:
                lines.append(f"    return dlt.read_stream({stage_fn!r})")
            else:
                lines.append(f"    return dlt.read({stage_fn!r})")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def render_databricks_sizing_md(result: DiscoveryResult) -> str:
    """Render a Databricks Lakeflow Connect CDC readiness & backfill sizing guide."""
    ov = result.overview
    lines: list[str] = [
        f"# Databricks Ingestion & CDC Readiness Plan: `{ov.database_name}`",
        "",
        f"- **Source:** `{ov.dialect}` ({ov.server_version or ov.driver})",
        f"- **Target Unity Catalog:** `{result.config.databricks_catalog}.{result.config.databricks_schema}`",
        f"- **CDC Ready / Blocked Tables:** `{ov.cdc_ready_table_count}` ready · `{ov.cdc_blocked_table_count}` blocked",
        f"- **Delta Compatibility Warnings:** `{ov.delta_warning_count}`",
        "",
    ]

    if ov.cdc_audit and ov.cdc_audit.notes:
        lines.append("## Database-Level CDC Audit")
        lines.append("")
        for note in ov.cdc_audit.notes:
            lines.append(f"- {note}")
        lines.append("")

    lines.append("## Table-by-Table Backfill Sizing, CDC & Liquid Clustering")
    lines.append("")
    lines.append(
        "| Source Table | Semantic Name | Rows | Est. Size (MB) | Est. Daily Rows | Cadence | CDC Status | Connector | Liquid Clustering (`CLUSTER BY`) | Databricks Tier |"
    )
    lines.append("|---|---|---:|---:|---:|---|---|---|---|---|")
    for tbl in result.tables:
        if tbl.table_type != "table":
            continue
        sz = tbl.ingestion_sizing
        cdc = tbl.cdc_readiness
        dc = tbl.delta_compatibility
        est_mb = f"{sz.estimated_size_mb:.2f}" if sz else "—"
        daily = f"{sz.estimated_daily_rows:,.0f}" if (sz and sz.estimated_daily_rows is not None) else "—"
        cadence = sz.recommended_cadence if sz else "—"
        tier = sz.recommended_databricks_tier if sz else "—"
        cdc_st = cdc.status.upper() if cdc else "—"
        conn = cdc.connector_recommendation if cdc else "—"
        lck = (
            ", ".join(f"`{_escape_md(k)}`" for k in dc.liquid_clustering_keys)
            if (dc and dc.liquid_clustering_keys)
            else "—"
        )
        lines.append(
            f"| `{_escape_md(tbl.full_name)}` | `{_escape_md(tbl.semantic_name)}` | {tbl.row_count or 0:,} | {est_mb} | {daily} | "
            f"`{_escape_md(cadence)}` | **{cdc_st}** | `{_escape_md(conn)}` | {lck} | {_escape_md(tier)} |"
        )
    lines.append("")

    # Delta compatibility lint summary
    lint_rows: list[str] = []
    for tbl in result.tables:
        if tbl.delta_compatibility:
            for iss in tbl.delta_compatibility.issues:
                lint_rows.append(
                    f"| **{iss.severity.upper()}** | `{_escape_md(tbl.full_name)}` | `{_escape_md(iss.column)}` | "
                    f"`{_escape_md(iss.category)}` | {_escape_md(iss.message)} | {_escape_md(iss.remediation)} |"
                )
    if lint_rows:
        lines.append("## Spark / Delta Lake Compatibility Linter")
        lines.append("")
        lines.append("| Severity | Table | Column | Category | Finding | Remediation |")
        lines.append("|---|---|---|---|---|---|")
        lines.extend(lint_rows)
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def export_databricks_bundle(
    result: DiscoveryResult,
    output_dir: str | Path,
    catalog: str | None = None,
    bronze_schema: str | None = None,
    silver_schema: str = "silver",
) -> list[Path]:
    """Write Unity Catalog DDL, Lakeflow DLT pipeline Python, and sizing guide to output_dir."""
    root = Path(output_dir)
    root.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    ddl_path = root / "unity_catalog_ddl.sql"
    ddl_path.write_text(
        render_unity_catalog_ddl(result, catalog=catalog, schema=bronze_schema),
        encoding="utf-8",
    )
    written.append(ddl_path)

    dlt_path = root / "lakeflow_pipeline.py"
    dlt_path.write_text(
        render_lakeflow_pipeline_py(
            result,
            catalog=catalog,
            bronze_schema=bronze_schema,
            silver_schema=silver_schema,
        ),
        encoding="utf-8",
    )
    written.append(dlt_path)

    sizing_path = root / "ingestion_sizing.md"
    sizing_path.write_text(render_databricks_sizing_md(result), encoding="utf-8")
    written.append(sizing_path)

    return written
