"""Snowflake DDL, Dynamic Tables, Data Metric Functions (DMFs), and sizing exporters."""

from __future__ import annotations

from pathlib import Path

from tick.models import ColumnInfo, DiscoveryResult, TableInfo
from tick.snowflake import (
    deduplicate_snowflake_columns,
    deduplicate_snowflake_tables,
    map_to_snowflake_type,
    sanitize_snowflake_identifier,
)


def _sq(val: str) -> str:
    """Escape a single-quoted SQL string literal for Snowflake."""
    return val.replace("\\", "\\\\").replace("'", "''").replace("\n", " ").replace("\r", " ")


def _dq(val: str) -> str:
    """Double-quote a Snowflake identifier safely."""
    return f'"{val.replace(chr(34), chr(34) * 2)}"'


def _escape_md(val: str | None) -> str:
    if not val:
        return "—"
    return val.replace("|", "\\|").replace("\n", " ").replace("\r", " ")


def _sf_mask_policy_name(sf_type: str) -> str:
    if sf_type.strip().upper() == "VARCHAR":
        return "MASK_SENSITIVE_VARCHAR"
    return f"MASK_SENSITIVE_{sanitize_snowflake_identifier(sf_type)}"


def _sf_row_policy_name(sf_type: str) -> str:
    if sf_type.strip().upper() == "VARCHAR":
        return "PLANT_ROW_ACCESS_POLICY"
    return f"PLANT_ROW_ACCESS_{sanitize_snowflake_identifier(sf_type)}"


def _target_lag_for_table(tbl: TableInfo) -> str:
    if tbl.telemetry_profile is not None:
        return "5 minutes"
    cadence = tbl.ingestion_sizing.recommended_cadence if tbl.ingestion_sizing else "daily_batch"
    if cadence == "continuous_streaming":
        return "1 minute"
    if cadence == "micro_batch_15m":
        return "15 minutes"
    if cadence == "hourly_batch":
        return "1 hour"
    return "1 day"


def _snowflake_legacy_date_expr(col: ColumnInfo, col_ref: str, paired_ref: str | None) -> str:
    """Translate a detected LegacyDateEncoding into native Snowflake SQL."""
    assert col.profile and col.profile.legacy_date
    enc = col.profile.legacy_date.encoding
    if enc in {"yyyymmdd_int", "yyyymmdd_str"}:
        if paired_ref:
            return (
                f"TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR({col_ref}) || "
                f"LPAD(TO_VARCHAR({paired_ref}), 6, '0'), 'YYYYMMDDHH24MISS')"
            )
        return f"TRY_TO_DATE(TO_VARCHAR({col_ref}), 'YYYYMMDD')"
    if enc == "julian_cyyddd":
        date_expr = (
            f"TRY_TO_DATE(TO_VARCHAR(TRY_TO_NUMBER(SUBSTR(TO_VARCHAR({col_ref}), 1, 1)) * 100 + 1900 "
            f"+ TRY_TO_NUMBER(SUBSTR(TO_VARCHAR({col_ref}), 2, 2))) || "
            f"SUBSTR(TO_VARCHAR({col_ref}), 4, 3), 'YYYYDDD')"
        )
        if paired_ref:
            return (
                f"TRY_TO_TIMESTAMP_NTZ(TO_CHAR({date_expr}, 'YYYYMMDD') || "
                f"LPAD(TO_VARCHAR({paired_ref}), 6, '0'), 'YYYYMMDDHH24MISS')"
            )
        return date_expr
    if enc == "julian_yyyyddd":
        date_expr = f"TRY_TO_DATE(TO_VARCHAR({col_ref}), 'YYYYDDD')"
        if paired_ref:
            return (
                f"TRY_TO_TIMESTAMP_NTZ(TO_CHAR({date_expr}, 'YYYYMMDD') || "
                f"LPAD(TO_VARCHAR({paired_ref}), 6, '0'), 'YYYYMMDDHH24MISS')"
            )
        return date_expr
    if enc == "excel_serial":
        date_expr = f"DATEADD('DAY', TRY_TO_NUMBER(TO_VARCHAR({col_ref})), TO_DATE('1899-12-30'))"
        if paired_ref:
            return (
                f"TRY_TO_TIMESTAMP_NTZ(TO_CHAR({date_expr}, 'YYYYMMDD') || "
                f"LPAD(TO_VARCHAR({paired_ref}), 6, '0'), 'YYYYMMDDHH24MISS')"
            )
        return date_expr
    return f"LPAD(TO_VARCHAR({col_ref}), 6, '0')"


def render_snowflake_ddl(
    result: DiscoveryResult,
    database: str | None = None,
    schema: str | None = None,
) -> str:
    """Generate Snowflake DDL with CHANGE_TRACKING, Object Tags, Row Access Policies, and Masking Policies."""
    db = database or result.config.snowflake_database
    sch = schema or result.config.snowflake_schema

    base_tables = [t for t in result.tables if t.table_type == "table"]
    tbl_name_map = deduplicate_snowflake_tables(base_tables)

    # Collect every governance tag key referenced by any table so CREATE TAG covers all SET TAG statements
    tag_idents: list[str] = ["PII", "PII_CATEGORY", "SENSITIVITY", "COMPLIANCE", "GOVERNANCE_SCOPE"]
    for tbl in base_tables:
        for col in tbl.columns:
            if col.profile:
                for gov in col.profile.governance_findings:
                    t_id = sanitize_snowflake_identifier(gov.uc_tag_key)
                    if t_id not in tag_idents:
                        tag_idents.append(t_id)

    lines: list[str] = [
        f"-- Auto-generated by tick for Snowflake ({db}.{sch})",
        f"-- Source: {result.overview.dialect} ({result.overview.database_name})",
        "",
        f"CREATE DATABASE IF NOT EXISTS {_dq(db)};",
        f"CREATE SCHEMA IF NOT EXISTS {_dq(db)}.{_dq(sch)};",
        "",
        "-- Governance Object Tags",
        *[f"CREATE TAG IF NOT EXISTS {_dq(db)}.{_dq(sch)}.{_dq(t_id)};" for t_id in tag_idents],
        "",
    ]

    # fqn -> (first_col_name, sf_type, extra_plant_cols)
    row_policy_tables: dict[str, tuple[str, str, list[str]]] = {}
    # (fqn, col_name) -> (sf_type, reasons)
    mask_columns: dict[tuple[str, str], tuple[str, list[str]]] = {}

    for tbl in base_tables:
        safe_tbl = tbl_name_map[tbl.full_name]
        col_map = deduplicate_snowflake_columns([c.name for c in tbl.columns])
        existing_sf_cols = set(col_map.values())
        fqn = f"{_dq(db)}.{_dq(sch)}.{_dq(safe_tbl)}"
        sfc = tbl.snowflake_compatibility
        est_mb = tbl.ingestion_sizing.estimated_size_mb if tbl.ingestion_sizing else 0.0

        lines.append(
            f"-- Source table: {tbl.full_name}"
            + (f" ({tbl.semantic_name})" if tbl.semantic_name else "")
        )
        lines.append(f"CREATE TABLE IF NOT EXISTS {fqn} (")

        col_defs: list[str] = []
        for col in tbl.columns:
            cname = col_map[col.name]
            stype = col.snowflake_type or map_to_snowflake_type(col.raw_type, col.canonical_type)
            nn = " NOT NULL" if (not col.nullable and col.is_primary_key) else ""
            comment_text = col.business_description or col.comment or (
                f"Source column: {col.name}" if cname != col.name else None
            )
            comment_sql = f" COMMENT '{_sq(comment_text)}'" if comment_text else ""
            col_defs.append(f"  {_dq(cname)} {stype}{nn}{comment_sql}")

        # Bronze audit metadata columns (skip if source table already carries them)
        if "_INGESTED_AT" not in existing_sf_cols:
            col_defs.append(
                "  \"_INGESTED_AT\" TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP() COMMENT 'Snowflake ingestion timestamp'"
            )
        if "_SOURCE_SYSTEM" not in existing_sf_cols:
            col_defs.append("  \"_SOURCE_SYSTEM\" VARCHAR COMMENT 'Originating plant / source system identifier'")

        if tbl.primary_key:
            pk_sql = ", ".join(
                _dq(col_map.get(p, sanitize_snowflake_identifier(p))) for p in tbl.primary_key
            )
            col_defs.append(f"  PRIMARY KEY ({pk_sql}) NOT ENFORCED")

        lines.append(",\n".join(col_defs))
        lines.append(")")
        lines.append("CHANGE_TRACKING = TRUE")

        if sfc and sfc.clustering_keys:
            ckeys = ", ".join(_dq(k) for k in sfc.clustering_keys)
            if est_mb >= 1024 or tbl.telemetry_profile is not None:
                lines.append(f"CLUSTER BY ({ckeys})")
            else:
                lines.append(f"-- Recommended CLUSTER BY ({ckeys}) once table exceeds ~1 GB")

        tcomment = tbl.business_description or tbl.comment or (
            f"Discovered from {tbl.full_name} (role: {tbl.recommendations.entity_role if tbl.recommendations else 'unknown'})"
        )
        lines.append(f"COMMENT = '{_sq(tcomment)}';")

        # Column-level Object Tags & Policy Registration
        for col in tbl.columns:
            cname = col_map[col.name]
            stype = col.snowflake_type or map_to_snowflake_type(col.raw_type, col.canonical_type)
            if not col.profile:
                continue
            if col.profile.pii_findings:
                cat_tag = col.profile.pii_findings[0].category
                lines.append(
                    f"ALTER TABLE {fqn} MODIFY COLUMN {_dq(cname)} SET TAG "
                    f"{_dq(db)}.{_dq(sch)}.{_dq('PII')} = 'true', "
                    f"{_dq(db)}.{_dq(sch)}.{_dq('PII_CATEGORY')} = '{_sq(cat_tag)}';"
                )
                entry = mask_columns.setdefault((fqn, cname), (stype, []))
                reason = f"pii_{cat_tag}"
                if reason not in entry[1]:
                    entry[1].append(reason)
            for gov in col.profile.governance_findings:
                tag_ident = sanitize_snowflake_identifier(gov.uc_tag_key)
                lines.append(
                    f"ALTER TABLE {fqn} MODIFY COLUMN {_dq(cname)} SET TAG "
                    f"{_dq(db)}.{_dq(sch)}.{_dq(tag_ident)} = '{_sq(gov.uc_tag_value)}';"
                )
                if gov.uc_policy == "row_filter":
                    if fqn not in row_policy_tables:
                        row_policy_tables[fqn] = (cname, stype, [])
                    elif cname != row_policy_tables[fqn][0] and cname not in row_policy_tables[fqn][2]:
                        row_policy_tables[fqn][2].append(cname)
                elif gov.uc_policy == "column_mask":
                    entry = mask_columns.setdefault((fqn, cname), (stype, []))
                    if gov.uc_tag_value not in entry[1]:
                        entry[1].append(gov.uc_tag_value)

        lines.append("")

    # Row Access Policies & Dynamic Data Masking Policies
    if row_policy_tables or mask_columns:
        lines.append("-- ============================================================================")
        lines.append("-- Snowflake Row Access Policies & Dynamic Data Masking Templates")
        lines.append("-- Review and customize role names before applying in production.")
        lines.append("-- ============================================================================")
        if row_policy_tables:
            seen_rp_types: list[str] = []
            for _, stype, _ in row_policy_tables.values():
                if stype not in seen_rp_types:
                    seen_rp_types.append(stype)
            for stype in seen_rp_types:
                pname = _sf_row_policy_name(stype)
                cmp_expr = (
                    "PLANT_VAL = CURRENT_USER()"
                    if stype.strip().upper() == "VARCHAR"
                    else "TO_VARCHAR(PLANT_VAL) = CURRENT_USER()"
                )
                lines.extend(
                    [
                        f"CREATE OR REPLACE ROW ACCESS POLICY {_dq(db)}.{_dq(sch)}.{_dq(pname)}",
                        f"AS (PLANT_VAL {stype}) RETURNS BOOLEAN ->",
                        "  IS_ROLE_IN_SESSION('GLOBAL_MANUFACTURING_ADMIN')",
                        f"  OR {cmp_expr}; -- Replace with plant-access entitlement lookup table",
                        "",
                    ]
                )
            for fqn, (col_name, stype, extra_cols) in row_policy_tables.items():
                pname = _sf_row_policy_name(stype)
                extra_note = (
                    f" -- Additional plant keys skipped (Snowflake allows 1 row access policy/table): {', '.join(extra_cols)}"
                    if extra_cols
                    else ""
                )
                lines.append(
                    f"-- ALTER TABLE {fqn} ADD ROW ACCESS POLICY {_dq(db)}.{_dq(sch)}.{_dq(pname)} ON ({_dq(col_name)});{extra_note}"
                )
            lines.append("")

        if mask_columns:
            mask_items = list(mask_columns.items())[:25]
            seen_mp_types: list[str] = []
            for _, (stype, _) in mask_items:
                if stype not in seen_mp_types:
                    seen_mp_types.append(stype)
            for stype in seen_mp_types:
                pname = _sf_mask_policy_name(stype)
                redacted_expr = (
                    "'***REDACTED***'"
                    if stype.strip().upper() == "VARCHAR"
                    else f"CAST(NULL AS {stype})"
                )
                lines.extend(
                    [
                        f"CREATE OR REPLACE MASKING POLICY {_dq(db)}.{_dq(sch)}.{_dq(pname)}",
                        f"AS (VAL {stype}) RETURNS {stype} ->",
                        f"  CASE WHEN IS_ROLE_IN_SESSION('SENSITIVE_DATA_READER') THEN VAL ELSE {redacted_expr} END;",
                        "",
                    ]
                )
            for (fqn, col_name), (stype, reasons) in mask_items:
                pname = _sf_mask_policy_name(stype)
                lines.append(
                    f"-- ALTER TABLE {fqn} MODIFY COLUMN {_dq(col_name)} SET MASKING POLICY {_dq(db)}.{_dq(sch)}.{_dq(pname)}; -- ({', '.join(reasons)})"
                )
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def render_snowflake_dynamic_tables_sql(
    result: DiscoveryResult,
    database: str | None = None,
    bronze_schema: str | None = None,
    silver_schema: str = "SILVER",
    warehouse: str | None = None,
) -> str:
    """Generate Snowflake Bronze -> Silver Dynamic Tables SQL with legacy date parsing, dedup, and OT filters."""
    db = database or result.config.snowflake_database
    bsch = bronze_schema or result.config.snowflake_schema
    wh = warehouse or result.config.snowflake_warehouse

    lines: list[str] = [
        f"-- Auto-generated by tick: Snowflake Bronze -> Silver Dynamic Tables ({db}.{silver_schema})",
        f"-- Source database: {result.overview.database_name} ({result.overview.dialect})",
        "",
        f"CREATE SCHEMA IF NOT EXISTS {_dq(db)}.{_dq(silver_schema)};",
        "",
    ]

    base_tables = [t for t in result.tables if t.table_type == "table"]
    tbl_name_map = deduplicate_snowflake_tables(base_tables)

    for tbl in base_tables:
        safe_tbl = tbl_name_map[tbl.full_name]
        col_map = deduplicate_snowflake_columns([c.name for c in tbl.columns])
        bronze_fqn = f"{_dq(db)}.{_dq(bsch)}.{_dq(safe_tbl)}"
        silver_fqn = f"{_dq(db)}.{_dq(silver_schema)}.{_dq(f'SILVER_{safe_tbl}')}"
        rec = tbl.recommendations
        strategy = rec.ingestion_strategy if rec else "full_refresh"
        lag = _target_lag_for_table(tbl)

        lines.append(
            f"-- --- {tbl.full_name}"
            + (f" ({tbl.semantic_name})" if tbl.semantic_name else "")
            + f" [{strategy}] ---"
        )
        if tbl.hierarchy:
            lines.append(
                f"-- NOTE: Recursive {tbl.hierarchy.pattern} detected ({tbl.hierarchy.parent_column} -> {tbl.hierarchy.child_column})."
            )
            lines.append("-- Build a downstream Gold BOM/genealogy model using WITH RECURSIVE or CONNECT BY.")

        select_exprs: list[str] = []
        emitted_cols: set[str] = set()
        for col in tbl.columns:
            cname = col_map[col.name]
            select_exprs.append(f"  {_dq(cname)}")
            emitted_cols.add(cname)

        # Legacy date/time parsing expressions in native Snowflake SQL
        for col in tbl.columns:
            if col.profile and col.profile.legacy_date:
                ld = col.profile.legacy_date
                cname = col_map[col.name]
                if ld.encoding == "hhmmss" and ld.paired_column:
                    continue
                target_col = f"{cname}_TS" if ld.paired_column else f"{cname}_PARSED"
                if target_col in emitted_cols:
                    suffix = 2
                    while f"{target_col}_{suffix}" in emitted_cols:
                        suffix += 1
                    target_col = f"{target_col}_{suffix}"
                emitted_cols.add(target_col)
                paired_ref = (
                    _dq(col_map.get(ld.paired_column, sanitize_snowflake_identifier(ld.paired_column)))
                    if ld.paired_column
                    else None
                )
                expr = _snowflake_legacy_date_expr(col, _dq(cname), paired_ref)
                select_exprs.append(f"  {expr} AS {_dq(target_col)}")

        if "_INGESTED_AT" not in emitted_cols:
            select_exprs.append('  "_INGESTED_AT"')
        if "_SOURCE_SYSTEM" not in emitted_cols:
            select_exprs.append('  "_SOURCE_SYSTEM"')

        lines.append(f"CREATE OR REPLACE DYNAMIC TABLE {silver_fqn}")
        lines.append(f"  TARGET_LAG = '{lag}'")
        lines.append(f"  WAREHOUSE = {_dq(wh)}")
        lines.append("AS")
        lines.append("SELECT")
        lines.append(",\n".join(select_exprs))
        lines.append(f"FROM {bronze_fqn}")

        # OT sensor quality filter
        where_clauses: list[str] = []
        if tbl.telemetry_profile and tbl.telemetry_profile.quality_column:
            raw_qcol = tbl.telemetry_profile.quality_column
            qcol = col_map.get(raw_qcol, sanitize_snowflake_identifier(raw_qcol))
            qcol_obj = next((c for c in tbl.columns if c.name == raw_qcol), None)
            if qcol_obj and qcol_obj.canonical_type in {"integer", "decimal", "float"}:
                where_clauses.append(f"{_dq(qcol)} >= 192")
            else:
                where_clauses.append(
                    f"UPPER(TO_VARCHAR({_dq(qcol)})) NOT IN ('BAD', 'UNCERTAIN', '0', 'FAULT', 'ERROR')"
                )
        if where_clauses:
            lines.append("WHERE " + " AND ".join(where_clauses))

        # Deduplication via QUALIFY ROW_NUMBER() for incremental_merge tables with PK + watermark
        raw_pks = tbl.primary_key or (rec.primary_key_candidates[:1] if rec else [])
        pk_cols = [col_map.get(p, sanitize_snowflake_identifier(p)) for p in raw_pks]
        wm_col = (
            col_map.get(
                rec.watermark_candidates[0].column,
                sanitize_snowflake_identifier(rec.watermark_candidates[0].column),
            )
            if (rec and rec.watermark_candidates)
            else None
        )
        if strategy == "incremental_merge" and pk_cols and wm_col:
            part_sql = ", ".join(_dq(c) for c in pk_cols)
            lines.append(
                f"QUALIFY ROW_NUMBER() OVER (PARTITION BY {part_sql} ORDER BY {_dq(wm_col)} DESC, \"_INGESTED_AT\" DESC) = 1"
            )

        lines[-1] = lines[-1] + ";"
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def render_snowflake_dmf_sql(
    result: DiscoveryResult,
    database: str | None = None,
    schema: str | None = None,
) -> str:
    """Generate Snowflake Data Metric Functions (DMFs) SQL for automated table quality monitoring."""
    db = database or result.config.snowflake_database
    sch = schema or result.config.snowflake_schema

    lines: list[str] = [
        f"-- Auto-generated by tick: Snowflake Data Metric Functions (DMFs) ({db}.{sch})",
        f"-- Source database: {result.overview.database_name} ({result.overview.dialect})",
        "-- Requires Snowflake Enterprise Edition (or higher) with DATA_METRIC_USER role.",
        "",
    ]

    base_tables = [t for t in result.tables if t.table_type == "table"]
    tbl_name_map = deduplicate_snowflake_tables(base_tables)
    custom_dmfs: list[str] = []
    has_opc_num_dmf = False

    for tbl in base_tables:
        safe_tbl = tbl_name_map[tbl.full_name]
        col_map = deduplicate_snowflake_columns([c.name for c in tbl.columns])
        fqn = f"{_dq(db)}.{_dq(sch)}.{_dq(safe_tbl)}"
        stmts: list[str] = []

        # Row count check
        stmts.append(
            f"ALTER TABLE {fqn} ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.ROW_COUNT ON ();"
        )

        # Primary key uniqueness & not-null checks
        if tbl.primary_key:
            pk_sql = ", ".join(
                _dq(col_map.get(p, sanitize_snowflake_identifier(p))) for p in tbl.primary_key
            )
            stmts.append(
                f"ALTER TABLE {fqn} ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.DUPLICATE_COUNT ON ({pk_sql});"
            )

        for col in tbl.columns:
            cname = col_map[col.name]
            prof = col.profile
            if col.is_primary_key or (not col.nullable and (prof is None or prof.null_rate == 0.0)):
                stmts.append(
                    f"ALTER TABLE {fqn} ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON ({_dq(cname)});"
                )

        # Freshness DMF on top temporal watermark (Snowflake FRESHNESS requires DATE/TIMESTAMP column)
        if tbl.recommendations and tbl.recommendations.watermark_candidates:
            col_by_name = {c.name: c for c in tbl.columns}
            temporal_wm = next(
                (
                    w
                    for w in tbl.recommendations.watermark_candidates
                    if w.kind in {"updated_at", "event_timestamp", "created_at"}
                    and w.column in col_by_name
                    and col_by_name[w.column].canonical_type in {"timestamp", "date"}
                ),
                None,
            )
            if temporal_wm:
                wcol = col_map.get(temporal_wm.column, sanitize_snowflake_identifier(temporal_wm.column))
                stmts.append(
                    f"ALTER TABLE {fqn} ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.FRESHNESS ON ({_dq(wcol)});"
                )

        # Numeric OPC Classic quality DMF (< 192)
        if tbl.telemetry_profile and tbl.telemetry_profile.quality_column:
            raw_qcol = tbl.telemetry_profile.quality_column
            qcol = col_map.get(raw_qcol, sanitize_snowflake_identifier(raw_qcol))
            qcol_obj = next((c for c in tbl.columns if c.name == raw_qcol), None)
            if qcol_obj and qcol_obj.canonical_type in {"integer", "decimal", "float"}:
                has_opc_num_dmf = True
                stmts.append(
                    f"ALTER TABLE {fqn} ADD DATA METRIC FUNCTION {_dq(db)}.{_dq(sch)}.{_dq('BAD_OPC_QUALITY_COUNT')} ON ({_dq(qcol)});"
                )

        if stmts:
            lines.append(f"-- {tbl.full_name}")
            lines.append(f"ALTER TABLE {fqn} SET DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES';")
            lines.extend(stmts)
            lines.append("")

    if has_opc_num_dmf:
        custom_dmfs.extend(
            [
                f"CREATE DATA METRIC FUNCTION IF NOT EXISTS {_dq(db)}.{_dq(sch)}.{_dq('BAD_OPC_QUALITY_COUNT')}(",
                "  ARG_T TABLE(ARG_C NUMBER)",
                ") RETURNS NUMBER AS",
                "$$",
                "  SELECT COUNT(*) FROM ARG_T WHERE ARG_C < 192",
                "$$;",
                "",
            ]
        )

    if custom_dmfs:
        # Insert custom DMF definitions right after the file header
        lines = lines[:4] + custom_dmfs + lines[4:]

    return "\n".join(lines).rstrip() + "\n"


def _snowflake_connector_rec(tbl: TableInfo, dialect: str) -> str:
    if dialect == "snowflake":
        return "snowflake_stream_dynamic_table"
    if tbl.telemetry_profile is not None:
        return "snowpipe_streaming"
    cdc_st = tbl.cdc_readiness.status if tbl.cdc_readiness else None
    if dialect in {"mssql", "postgresql", "oracle", "mysql"} and cdc_st == "ready":
        return f"snowflake_openflow_{dialect}_cdc"
    if tbl.recommendations and tbl.recommendations.ingestion_strategy in {"incremental_merge", "incremental_append"}:
        return "copy_into_or_openflow_incremental"
    return "copy_into_full_refresh"


def render_snowflake_sizing_md(
    result: DiscoveryResult,
    database: str | None = None,
    schema: str | None = None,
    warehouse: str | None = None,
) -> str:
    """Render a Snowflake ingestion, Dynamic Tables lag, Warehouse sizing, and compatibility guide."""
    ov = result.overview
    db = database or result.config.snowflake_database
    sch = schema or result.config.snowflake_schema
    wh = warehouse or result.config.snowflake_warehouse
    lines: list[str] = [
        f"# Snowflake Ingestion, Dynamic Tables & Sizing Plan: `{ov.database_name}`",
        "",
        f"- **Source:** `{ov.dialect}` ({ov.server_version or ov.driver})",
        f"- **Target Snowflake Location:** `{db}.{sch}` (Warehouse: `{wh}`)",
        f"- **CDC Ready / Blocked Tables:** `{ov.cdc_ready_table_count}` ready · `{ov.cdc_blocked_table_count}` blocked",
        f"- **Snowflake Compatibility Warnings:** `{ov.snowflake_warning_count}`",
        "",
        "## Table-by-Table Backfill Sizing, Dynamic Tables & Warehouse Plan",
        "",
        "| Source Table | Semantic Name | Rows | Est. Size (MB) | Est. Daily Rows | Dynamic Table Lag | Connector | Clustering Keys | Warehouse |",
        "|---|---|---:|---:|---:|---|---|---|---|",
    ]

    for tbl in result.tables:
        if tbl.table_type != "table":
            continue
        sz = tbl.ingestion_sizing
        sfc = tbl.snowflake_compatibility
        est_mb = f"{sz.estimated_size_mb:.2f}" if sz else "—"
        daily = f"{sz.estimated_daily_rows:,.0f}" if (sz and sz.estimated_daily_rows is not None) else "—"
        lag = _target_lag_for_table(tbl)
        conn = _snowflake_connector_rec(tbl, ov.dialect)
        ck = (
            ", ".join(f"`{_escape_md(k)}`" for k in sfc.clustering_keys)
            if (sfc and sfc.clustering_keys)
            else "—"
        )
        wh_sz = sfc.recommended_warehouse_size if sfc else "XSMALL"
        lines.append(
            f"| `{_escape_md(tbl.full_name)}` | `{_escape_md(tbl.semantic_name)}` | {tbl.row_count or 0:,} | "
            f"{est_mb} | {daily} | `{lag}` | `{conn}` | {ck} | `{wh_sz}` |"
        )
    lines.append("")

    lint_rows: list[str] = []
    for tbl in result.tables:
        if tbl.snowflake_compatibility:
            for iss in tbl.snowflake_compatibility.issues:
                lint_rows.append(
                    f"| **{iss.severity.upper()}** | `{_escape_md(tbl.full_name)}` | `{_escape_md(iss.column)}` | "
                    f"`{_escape_md(iss.category)}` | {_escape_md(iss.message)} | {_escape_md(iss.remediation)} |"
                )
    if lint_rows:
        lines.append("## Snowflake Compatibility Linter")
        lines.append("")
        lines.append("| Severity | Table | Column | Category | Finding | Remediation |")
        lines.append("|---|---|---|---|---|---|")
        lines.extend(lint_rows)
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def export_snowflake_bundle(
    result: DiscoveryResult,
    output_dir: str | Path,
    database: str | None = None,
    schema: str | None = None,
    warehouse: str | None = None,
) -> list[Path]:
    """Write Snowflake DDL, Dynamic Tables SQL, DMFs SQL, and sizing plan to output_dir."""
    root = Path(output_dir)
    root.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    ddl_path = root / "snowflake_ddl.sql"
    ddl_path.write_text(
        render_snowflake_ddl(result, database=database, schema=schema), encoding="utf-8"
    )
    written.append(ddl_path)

    dt_path = root / "snowflake_dynamic_tables.sql"
    dt_path.write_text(
        render_snowflake_dynamic_tables_sql(
            result, database=database, bronze_schema=schema, warehouse=warehouse
        ),
        encoding="utf-8",
    )
    written.append(dt_path)

    dmf_path = root / "snowflake_dmf.sql"
    dmf_path.write_text(
        render_snowflake_dmf_sql(result, database=database, schema=schema), encoding="utf-8"
    )
    written.append(dmf_path)

    sizing_path = root / "snowflake_sizing.md"
    sizing_path.write_text(
        render_snowflake_sizing_md(result, database=database, schema=schema, warehouse=warehouse),
        encoding="utf-8",
    )
    written.append(sizing_path)

    return written
