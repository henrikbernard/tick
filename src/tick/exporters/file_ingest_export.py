"""File / Data Lake ingestion SQL exporters: Databricks Auto Loader/COPY INTO & Snowflake FILE FORMAT/Snowpipe."""

from __future__ import annotations

from tick.databricks import deduplicate_table_names
from tick.models import DiscoveryResult, FileSourceInfo, TableInfo
from tick.snowflake import deduplicate_snowflake_tables, sanitize_snowflake_identifier


def _bt(val: str) -> str:
    return f"`{val.replace('`', '``')}`"


def _dq(val: str) -> str:
    return f'"{val.replace(chr(34), chr(34) * 2)}"'


def _sq(val: str) -> str:
    return val.replace("\\", "\\\\").replace("'", "''")


def has_file_sources(result: DiscoveryResult) -> bool:
    """Return True if at least one discovered table originated from a local/data-lake file source."""
    return any(t.table_type == "table" and t.file_source is not None for t in result.tables)


def _dbx_read_files_format(fs: FileSourceInfo) -> str:
    if fs.file_format in {"parquet", "delta"}:
        return "parquet"
    if fs.file_format in {"csv", "tsv"}:
        return "csv"
    return "json"


def render_databricks_autoloader_sql(
    result: DiscoveryResult,
    catalog: str | None = None,
    schema: str | None = None,
    volume_name: str = "landing_zone",
) -> str:
    """Generate Databricks SQL COPY INTO / read_files() ingestion scripts for discovered flat/data-lake files."""
    cat = catalog or result.config.databricks_catalog
    sch = schema or result.config.databricks_schema
    base_tables = [t for t in result.tables if t.table_type == "table"]
    tbl_name_map = deduplicate_table_names(base_tables)
    file_tables = [t for t in base_tables if t.file_source is not None]

    lines: list[str] = [
        f"-- Auto-generated by tick: Databricks Auto Loader / COPY INTO File Ingestion ({cat}.{sch})",
        f"-- Source landing zone: {result.overview.database_name} ({result.overview.sanitized_url})",
        "",
        f"CREATE CATALOG IF NOT EXISTS {_bt(cat)};",
        f"CREATE SCHEMA IF NOT EXISTS {_bt(cat)}.{_bt(sch)};",
        f"CREATE VOLUME IF NOT EXISTS {_bt(cat)}.{_bt(sch)}.{_bt(volume_name)};",
        "",
    ]

    if not file_tables:
        lines.append("-- No flat-file or data-lake sources in this snapshot.")
        return "\n".join(lines) + "\n"

    for tbl in file_tables:
        assert tbl.file_source is not None
        fs = tbl.file_source
        safe_tbl = tbl_name_map[tbl.full_name]
        fqn = f"{_bt(cat)}.{_bt(sch)}.{_bt(safe_tbl)}"
        vol_path = f"/Volumes/{cat}/{sch}/{volume_name}/{safe_tbl}/"

        lines.append(
            f"-- Source: {fs.path} ({fs.file_format.upper()}, {fs.file_count} file(s), {fs.total_bytes:,} bytes)"
        )
        if fs.file_format == "delta":
            lines.extend(
                [
                    f"CREATE TABLE IF NOT EXISTS {fqn}",
                    f"SHALLOW CLONE delta.`{vol_path}`; -- Or replace path with s3:// / abfss:// Delta table root",
                    "",
                ]
            )
            continue

        fmt = _dbx_read_files_format(fs)
        fmt_opts: list[str] = []
        if fmt == "csv":
            fmt_opts.append(f"'header' = '{'true' if fs.has_header is not False else 'false'}'")
            delim = fs.delimiter or ("\t" if fs.file_format == "tsv" else ",")
            delim_sql = "\\t" if delim == "\t" else _sq(delim)
            fmt_opts.append(f"'sep' = '{delim_sql}'")
            fmt_opts.append("'inferSchema' = 'true'")
        elif fmt == "json":
            if fs.file_format == "json":
                fmt_opts.append("'multiLine' = 'true'")
            fmt_opts.append("'inferSchema' = 'true'")

        lines.append(f"COPY INTO {fqn}")
        lines.append(f"FROM '{_sq(vol_path)}'")
        lines.append(f"FILEFORMAT = {fmt.upper()}")
        if fmt_opts:
            lines.append(f"FORMAT_OPTIONS ({', '.join(fmt_opts)})")
        lines.append("COPY_OPTIONS ('mergeSchema' = 'true');")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def _sf_format_key(fs: FileSourceInfo) -> tuple[str, str]:
    if fs.file_format in {"parquet", "delta"}:
        return "TICK_FMT_PARQUET", "TYPE = 'PARQUET'"
    if fs.file_format == "tsv":
        skip = 1 if fs.has_header is not False else 0
        comp = "COMPRESSION = 'GZIP'" if fs.compression == "gzip" else "COMPRESSION = 'AUTO'"
        return "TICK_FMT_TSV", f"TYPE = 'CSV' FIELD_DELIMITER = '\\t' SKIP_HEADER = {skip} FIELD_OPTIONALLY_ENCLOSED_BY = '\"' {comp}"
    if fs.file_format == "csv":
        skip = 1 if fs.has_header is not False else 0
        delim = fs.delimiter or ","
        delim_sql = "\\t" if delim == "\t" else _sq(delim)
        comp = "COMPRESSION = 'GZIP'" if fs.compression == "gzip" else "COMPRESSION = 'AUTO'"
        suffix = "" if delim == "," else f"_{sanitize_snowflake_identifier(delim)}"
        return (
            f"TICK_FMT_CSV{suffix}",
            f"TYPE = 'CSV' FIELD_DELIMITER = '{delim_sql}' SKIP_HEADER = {skip} FIELD_OPTIONALLY_ENCLOSED_BY = '\"' {comp}",
        )
    strip = "TRUE" if fs.file_format == "json" else "FALSE"
    comp = "COMPRESSION = 'GZIP'" if fs.compression == "gzip" else "COMPRESSION = 'AUTO'"
    fname = "TICK_FMT_JSON_ARRAY" if fs.file_format == "json" else "TICK_FMT_JSONL"
    return fname, f"TYPE = 'JSON' STRIP_OUTER_ARRAY = {strip} {comp}"


def render_snowflake_file_ingest_sql(
    result: DiscoveryResult,
    database: str | None = None,
    schema: str | None = None,
    stage_name: str = "TICK_LANDING_STAGE",
) -> str:
    """Generate Snowflake FILE FORMAT, STAGE, COPY INTO, and Snowpipe DDL for discovered flat/data-lake files."""
    db = database or result.config.snowflake_database
    sch = schema or result.config.snowflake_schema
    base_tables = [t for t in result.tables if t.table_type == "table"]
    tbl_name_map = deduplicate_snowflake_tables(base_tables)
    file_tables = [t for t in base_tables if t.file_source is not None]

    lines: list[str] = [
        f"-- Auto-generated by tick: Snowflake File Formats, Stage, COPY INTO & Snowpipe ({db}.{sch})",
        f"-- Source landing zone: {result.overview.database_name} ({result.overview.sanitized_url})",
        "",
        f"CREATE DATABASE IF NOT EXISTS {_dq(db)};",
        f"CREATE SCHEMA IF NOT EXISTS {_dq(db)}.{_dq(sch)};",
        "",
    ]

    if not file_tables:
        lines.append("-- No flat-file or data-lake sources in this snapshot.")
        return "\n".join(lines) + "\n"

    # Collect unique FILE FORMAT definitions needed
    formats_seen: dict[str, str] = {}
    for tbl in file_tables:
        assert tbl.file_source is not None
        fname, fspec = _sf_format_key(tbl.file_source)
        formats_seen.setdefault(fname, fspec)

    lines.append("-- 1. Reusable File Formats")
    for fname, fspec in formats_seen.items():
        lines.append(f"CREATE FILE FORMAT IF NOT EXISTS {_dq(db)}.{_dq(sch)}.{_dq(fname)} {fspec};")
    lines.append("")

    stage_fqn = f"{_dq(db)}.{_dq(sch)}.{_dq(stage_name)}"
    lines.extend(
        [
            "-- 2. Internal or External Landing Stage (add URL='s3://...' STORAGE_INTEGRATION=... for cloud storage)",
            f"CREATE STAGE IF NOT EXISTS {stage_fqn};",
            "",
            "-- 3. Batch COPY INTO & Continuous Snowpipe Templates",
        ]
    )

    for tbl in file_tables:
        assert tbl.file_source is not None
        fs = tbl.file_source
        safe_tbl = tbl_name_map[tbl.full_name]
        fqn = f"{_dq(db)}.{_dq(sch)}.{_dq(safe_tbl)}"
        fname, _ = _sf_format_key(fs)
        fmt_fqn = f"{_dq(db)}.{_dq(sch)}.{_dq(fname)}"
        pipe_fqn = f"{_dq(db)}.{_dq(sch)}.{_dq(f'PIPE_{safe_tbl}')}"
        stage_subpath = f"@{stage_fqn}/{safe_tbl.lower()}/"

        match_clause = (
            "MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE\n"
            if fs.file_format in {"parquet", "delta", "json", "jsonl"}
            else ""
        )
        lines.extend(
            [
                f"-- Source: {fs.path} ({fs.file_format.upper()}, {fs.file_count} file(s), {fs.total_bytes:,} bytes)",
                f"COPY INTO {fqn}",
                f"FROM {stage_subpath}",
                f"FILE_FORMAT = (FORMAT_NAME = {fmt_fqn})",
                f"{match_clause}ON_ERROR = 'CONTINUE';",
                "",
                f"-- Optional continuous Snowpipe (requires cloud event notification on external stage):",
                f"-- CREATE PIPE IF NOT EXISTS {pipe_fqn} AUTO_INGEST = TRUE AS",
                f"-- COPY INTO {fqn}",
                f"-- FROM {stage_subpath}",
                f"-- FILE_FORMAT = (FORMAT_NAME = {fmt_fqn})",
                f"-- {'MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ' if match_clause else ''}ON_ERROR = 'CONTINUE';",
                "",
            ]
        )

    return "\n".join(lines).rstrip() + "\n"
